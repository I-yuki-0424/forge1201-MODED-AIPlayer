function parseArgs(argv) {
    const o = { root: '/exchange', runId: null, seed: 1, reps: 10, only: null, bots: 10, trials: null, follow: null, waitLogin: 0, pregen: false, sites: null };
    const map = { '--root': ['root'], '--run-id': ['runId'], '--seed': ['seed', Number], '--reps': ['reps', Number], '--bots': ['bots', Number],
        '--only': ['only', (s) => s.split(',')], '--trials': ['trials', (s) => s.split(',').map(Number)], '--follow': ['follow'],
        '--wait-login': ['waitLogin', Number], '--pregen': ['pregen', (v) => v === '1'], '--sites': ['sites'] };
    for (let i = 0; i < argv.length; i += 2) {
        const [k, v] = [argv[i], argv[i + 1]];
        if (!map[k] || v === undefined) throw new Error(`bad argument ${k}`);
        o[map[k][0]] = map[k][1] ? map[k][1](v) : v;
    }
    if (!o.runId && !o.pregen) throw new Error('--run-id is required');
    if (o.follow && !/^[A-Za-z0-9_]{3,16}$/.test(o.follow)) throw new Error('--follow: a player name');
    if (!(o.bots >= 1 && o.bots <= 16)) throw new Error('--bots 1..16');
    for (const c of o.only || []) if (!COMMANDS[c]) throw new Error(`unknown command ${c}`);
    return o;
}

// ---------------------------------------------------------------- terrain as the client sees it (static during setup)
const at = (bot, x, y, z) => bot.blockAt(new Vec3(x, y, z));
const fluid = (b) => !!b && (b.name === 'water' || b.name === 'lava' || b.name === 'bubble_column' || !!b.getProperties?.().waterlogged);
const solid = (b) => !!b && b.boundingBox === 'block' && !fluid(b);
const open = (b) => !!b && b.boundingBox === 'empty' && !fluid(b) && !/fire|powder_snow|sweet_berry|cobweb/.test(b.name);
const TREE = /leaves|_log$|_wood$|mangrove_roots/;
// Standable by the bot's own world model (src/skills/world.js), so the harness never picks a cell the bot calls invalid
// (measured: bamboo and lily pads were "ground" for a plain collision test).
const { kindOf } = require('../../src/skills/world');
const standable = (bot, x, y, z) => kindOf(at(bot, x, y - 1, z)) === 'solid' && open(at(bot, x, y, z)) && open(at(bot, x, y + 1, z));

/** Highest non-open block of a column: {y, b} (y = that block's level). */
function top(bot, x, z) {
    for (let y = 319; y > -64; y--) { const b = at(bot, x, y, z); if (!b) return null; if (!open(b)) return { y, b }; }
    return null;
}

/** Cells reachable on foot from s (step up 1, drop up to 3), within AREA blocks. Sorted, so picks are deterministic. */
function reachable(bot, s) {
    const seen = new Map([[`${s.x},${s.y},${s.z}`, { ...s, d: 0 }]]), q = [s];
    while (q.length) {
        const c = q.shift();
        for (const [dx, dz] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
            const x = c.x + dx, z = c.z + dz;
            if (Math.hypot(x - s.x, z - s.z) > AREA) continue;
            for (const dy of [0, 1, -1, -2, -3]) {
                const y = c.y + dy;
                if (dy === 1 && !open(at(bot, c.x, c.y + 2, c.z))) continue;           // head room for the jump
                if (dy < 0 && ![0, 1].every((k) => open(at(bot, x, c.y + k, z)))) continue;
                if (!standable(bot, x, y, z)) continue;
                const k = `${x},${y},${z}`;
                if (!seen.has(k)) { const n = { x, y, z, d: Math.hypot(x - s.x, z - s.z) }; seen.set(k, n); q.push(n); }
                break;
            }
        }
    }
    return [...seen.values()].sort((a, b) => a.x - b.x || a.z - b.z || a.y - b.y);
}

// ---------------------------------------------------------------- sites
/** Trial n's candidate cells: perm[n], perm[n + T] (a seeded permutation of the region grid without the spawn area). */
function siteCandidates(seed, n, T) {
    const rng = mulberry32((seed ^ 0x5eed5) >>> 0), lim = REGION - SPACING, cells = [];
    for (let gx = -lim; gx <= lim; gx += SPACING) for (let gz = -lim; gz <= lim; gz += SPACING) {
        if (Math.abs(gx) <= SPACING && Math.abs(gz) <= SPACING) continue;          // keep the spawn area for players
        cells.push([gx + int(rng, -12, 12), gz + int(rng, -12, 12)]);
    }
    for (let i = cells.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [cells[i], cells[j]] = [cells[j], cells[i]]; }
    if (2 * T > cells.length) throw new Error(`${T} trials need ${2 * T} sites, the region has ${cells.length}`);
    return [cells[n], cells[n + T]];
}

/** Generate the test region once per world: a spectator scout visits a grid of points and waits for each view to load. */
async function pregen(o) {
    const B = await connectBot('MapScout', o), { bot, S } = B;
    // --sites: the training start sites (src/rl/run_skill_env.js --sites) instead of the region; also records what stands at
    // each site in the marker (the ground under the owner's feet coordinates), so a wrong seed or a wet site shows before training.
    const sites = o.sites ? require('../../src/rl/run_skill_env').loadSites(o.sites) : null;
    const mark = path.join(o.root, `pregen-${(/\[(-?\d+)\]/.exec(await S.cmd('seed')) || [])[1]}${sites ? '-sites' : ''}.json`);
    if (fs.existsSync(mark)) { console.log(`[lv2] already generated (${mark})`); return finish(); }
    await S.must(`gamemode spectator ${S.name}`);
    // A view loads +-8 chunks; points at most 224 blocks apart, ends at +-(REGION - 112), cover |x|, |z| <= REGION.
    const k = Math.ceil((2 * (REGION - 112)) / 224) + 1, axis = Array.from({ length: k }, (_, i) => Math.round(-REGION + 112 + (i * 2 * (REGION - 112)) / (k - 1)));
    const pts = sites ? sites.map(([x, , z]) => [x, z]) : axis.flatMap((x) => axis.map((z) => [x, z]));
    const ground = [];
    const t0 = Date.now();
    for (const [i, [x, z]] of pts.entries()) {
        await S.must(`tp ${S.name} ${x} 200 ${z}`);
        const r = sites ? 48 : 112;                                      // a site: the bot's own area (it views +-5 chunks)
        await waitFor(`region ${x},${z}`, () => [[-r, -r], [r, r], [-r, r], [r, -r]].every(([dx, dz]) => bot.blockAt(new Vec3(x + dx, 0, z + dz))), 180000);
        for (;;) {                                                       // let the server catch up before the next view
            const ms = parseFloat((/Mean tick time: ([\d.]+)/.exec(await S.cmd('forge tps overworld')) || [])[1]);
            if (!(ms > 40)) break;
            await sleep(2000);
        }
        if (sites) {
            const y = sites[i][1], name = (dy) => (at(bot, x, y + dy, z) || {}).name;
            ground.push({ site: sites[i], below: name(-1), feet: name(0), head: name(1), standable: standable(bot, x, y, z) });
        }
        console.log(`[lv2] pregen ${i + 1}/${pts.length} at ${x},${z} (${Math.round((Date.now() - t0) / 1000)} s)${sites ? ` ${JSON.stringify(ground[i])}` : ''}`);
    }
    fs.writeFileSync(mark, JSON.stringify({ region: sites ? undefined : REGION, points: pts.length, seconds: Math.round((Date.now() - t0) / 1000), ground: sites ? ground : undefined }));
    return finish();
    function finish() { shared.close(); bot.end(); setTimeout(() => process.exit(0), 500); }
}

/** At most `n` holders at once (new sites cost the server chunk generation; ten at once put it 40 ticks behind). */
function gate(n) {
    let free = n; const wait = [];
    return async (fn) => {
        if (free > 0) free--; else await new Promise((r) => wait.push(r));
        try { return await fn(); } finally { const next = wait.shift(); if (next) next(); else free++; }
    };
}
const loading = gate(2);

/** Load the area around (x, z) and pick the start: the dry ground cell nearest the centre with enough walkable room. */
async function chooseSite(bot, S, cx, cz) {
    // Onto the top block of the (pre-generated) site in survival: no fall, no spectator.
    await S.must(`gamemode survival ${S.name}`);
    const out = await S.cmd(`spreadplayers ${cx} ${cz} 0 3 false ${S.name}`);
    if (!/^Spread/.test(out)) return null;
    await waitFor('site chunks', () => [[-AREA - 2, -AREA - 2], [AREA + 2, AREA + 2], [0, 0]].every(([dx, dz]) => top(bot, cx + dx, cz + dz)), 60000);
    for (let r = 0; r <= 24; r++) for (let dx = -r; dx <= r; dx++) for (let dz = -r; dz <= r; dz++) {     // rings, nearest first
        if (Math.max(Math.abs(dx), Math.abs(dz)) !== r) continue;
        const x = cx + dx, z = cz + dz, t = top(bot, x, z);
        if (!t || TREE.test(t.b.name) || kindOf(t.b) !== 'solid') continue;
        const s = { x, y: t.y + 1, z };
        if (!standable(bot, s.x, s.y, s.z)) continue;
        const R = reachable(bot, s);
        if (R.length >= 80) return { start: s, R };
    }
    return null;
}

// ---------------------------------------------------------------- scenarios on natural terrain
/** A reachable cell at distance [lo, hi] from the start, not in `used`, passing `ok`. */
function cell(rng, W, lo, hi, ok = () => true) {
    const c = W.R.filter((n) => n.d >= lo && n.d <= hi && !W.used.has(`${n.x},${n.z}`) && ok(n));
    if (!c.length) throw new Error(`no natural cell at ${lo}-${hi}`);
    const n = pick(rng, c);
    W.used.add(`${n.x},${n.z}`);
    return { x: n.x, y: n.y, z: n.z };
}
const isAir = (b) => !!b && (b.name === 'air' || b.name === 'cave_air');

