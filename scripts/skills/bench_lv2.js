// LV2 benchmark of the command layer (test code): the same 14 commands as bench.js, but on untouched natural terrain.
// Nothing is flattened. Every trial gets its own site far from every other one (a seeded permutation of a 96-block grid),
// the bot stands on the real ground there, targets are real terrain cells the bot can walk to (trees, slopes, water and
// animals stay as generated), stations (chest, barrel, furnace, crafting table) are set on the natural ground, and hostile
// mobs are summoned around the bot in every trial. Several bots run trials in parallel, each at its own site.
// Grading is the server's state over RCON, as in bench.js.
//
// Server load (measured 2026-11-01: ten bots entering ten never-generated sites put the 3-CPU server 224 ticks behind and
// it dropped every bot): sites lie only inside a region generated beforehand, once per world, by one scout (--pregen), so
// bots load stored chunks instead of generating them. Bots enter a site with spreadplayers in survival (no spectator).
